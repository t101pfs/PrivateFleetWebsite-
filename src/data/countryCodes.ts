// World calling codes (ITU E.164 country codes), one entry per country.
// GCC first (where Private Fleet actually operates), then every other
// country alphabetically by name - so a charter client from anywhere
// (Russia, Nigeria, wherever) can be found, not just the handful of
// markets this list used to cover.
export interface CountryCode {
  code: string;
  iso2: string;
  country: string;
}

// Flag emoji is two "regional indicator" characters derived from the ISO
// 3166-1 alpha-2 code (e.g. "SA" -> 🇸🇦) - computed instead of hand-typed
// per row, so there's no chance of a flag/country mismatch across ~195 rows.
export function flagFromIso2(iso2: string): string {
  return iso2
    .toUpperCase()
    .replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt(0)));
}

