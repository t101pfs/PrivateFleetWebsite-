const CATEGORY_ICONS: Record<string, string> = {
  'Smileys & People': '😀',
  'Animals & Nature': '🐶',
  'Food & Drink': '🍔',
  'Activities': '⚽',
  'Travel & Places': '✈️',
  'Objects': '💡',
  'Symbols': '❤️',
  'Flags': '🏳️',
};

export function EmojiPicker({ onEmojiSelect }: EmojiPickerProps) {
  const [selectedCategory, setSelectedCategory] = useState<string>('Smileys & People');
  const [open, setOpen] = useState(false);

  const handleEmojiClick = (emoji: string) => {
    onEmojiSelect(emoji);
    setOpen(false);
  };

  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger asChild>
        <Button variant="ghost" size="icon" className="h-10 w-10">
          <Smile className="h-5 w-5 text-muted-foreground" />
        </Button>
      </PopoverTrigger>
      <PopoverContent 
        className="w-80 p-0 bg-popover" 
        align="end"
        side="top"
      >
        {/* Category tabs */}
        <div className="flex border-b border-border p-1 gap-0.5 overflow-x-auto">
          {Object.keys(EMOJI_CATEGORIES).map((category) => (
            <button
              key={category}
              onClick={() => setSelectedCategory(category)}
              className={cn(
                "flex-shrink-0 p-2 rounded-md text-lg hover:bg-accent/20 transition-colors",
                selectedCategory === category && "bg-accent/20"
              )}
              title={category}
            >
              {CATEGORY_ICONS[category]}
            </button>
          ))}
        </div>

        {/* Emoji grid */}
        <div className="h-64 overflow-y-auto p-2">
          <div className="grid grid-cols-8 gap-1">
            {EMOJI_CATEGORIES[selectedCategory as keyof typeof EMOJI_CATEGORIES].map((emoji, index) => (
              <button
                key={`${emoji}-${index}`}
                onClick={() => handleEmojiClick(emoji)}
                className="p-1.5 text-xl hover:bg-accent/20 rounded transition-colors"
              >
                {emoji}
              </button>
            ))}
          </div>
        </div>
      </PopoverContent>
    </Popover>
  );
}
